#!/usr/bin/env python3
"""Turn a PSF1 8x16 console font into kernel/font8x16.c.

Usage:  python3 tools/make_font.py <font.psf> kernel/font8x16.c

The source font is Lat15-VGA16.psf from Debian's console-setup package
(install: sudo apt install console-setup-linux; file is under
/usr/share/consolefonts/). PSF1 layout: 2 magic bytes (0x36 0x04),
1 mode byte, 1 character-size byte (16), then 256 glyphs of 16 bytes each.
Each glyph byte is one row of 8 pixels, most significant bit on the left.
"""
import sys

MAGIC = b"\x36\x04"
CHARSIZE = 16
GLYPHS = 256


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    src, dst = sys.argv[1], sys.argv[2]
    data = open(src, "rb").read()
    if data[:2] != MAGIC:
        print("not a PSF1 font:", src)
        return 1
    if data[3] != CHARSIZE:
        print("expected 16-row glyphs, got", data[3])
        return 1
    glyphs = data[4:4 + GLYPHS * CHARSIZE]
    if len(glyphs) != GLYPHS * CHARSIZE:
        print("font file is too short")
        return 1

    lines = [
        "/* 8x16 bitmap font, glyphs 0-255 in code-page order.",
        " * Generated by tools/make_font.py from Lat15-VGA16.psf (Debian console-setup).",
        " * Glyph bitmaps: Copyright (c) 2000, 2001 Dmitry Bolkhovityanov, MIT-style",
        " * permission. The full notice is in THIRD-PARTY-NOTICES.md at the repo root.",
        " * One byte per glyph row, most significant bit on the left. */",
        '#include <stdint.h>',
        '#include "font.h"',
        "",
        "const uint8_t font8x16_data[FONT_GLYPHS * FONT_HEIGHT] = {",
    ]
    for g in range(GLYPHS):
        chunk = glyphs[g * CHARSIZE:(g + 1) * CHARSIZE]
        row = ", ".join("0x%02X" % b for b in chunk)
        lines.append("    %s, /* %3d '%s' */" % (row, g, chr(g) if 32 <= g < 127 else "."))
    lines.append("};")
    lines.append("")
    open(dst, "w", newline="\n").write("\n".join(lines))
    print("wrote", dst)
    return 0


if __name__ == "__main__":
    sys.exit(main())
